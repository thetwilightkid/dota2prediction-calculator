// Reads the compact "product" JSON files produced by the Python pipeline in
// prediction/*.json and bakes them into typed TypeScript modules under
// website/data/. The site never invokes Python or fetches these at runtime -
// this script is the only bridge, run via `npm run build-data` (and
// automatically before `npm run build`).
const fs = require("fs");
const path = require("path");

const PREDICTION_DIR = path.resolve(__dirname, "..", "..");
const DATA_DIR = path.resolve(__dirname, "..", "data");

function readJson(filename) {
  const p = path.join(PREDICTION_DIR, filename);
  return JSON.parse(fs.readFileSync(p, "utf-8"));
}

function writeModule(filename, header, exportsSrc) {
  const banner =
    "// AUTO-GENERATED by scripts/build-dataset.js - do not edit by hand.\n" +
    "// Regenerate with `npm run build-data` after the Python pipeline updates prediction/*.json.\n\n";
  fs.writeFileSync(path.join(DATA_DIR, filename), banner + header + "\n" + exportsSrc, "utf-8");
  console.log(`  wrote data/${filename}`);
}

